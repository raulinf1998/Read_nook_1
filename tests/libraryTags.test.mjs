import assert from 'node:assert/strict';
import { test } from 'node:test';
import { JSDOM } from 'jsdom';
import { createServer } from 'vite';

test('Biblioteca filtra por etiqueta junto al estado y permite limpiar filtros', async (t) => {
  const dom = new JSDOM('<!doctype html><div id="root"></div>', { url: 'http://bilibook.test/' });
  globalThis.window = dom.window; globalThis.document = dom.window.document;
  Object.defineProperty(globalThis, 'navigator', { value: dom.window.navigator, configurable: true });
  globalThis.IS_REACT_ACT_ENVIRONMENT = true;
  const React = await import('react');
  const { createRoot } = await import('react-dom/client');
  const vite = await createServer({ server: { middlewareMode: true }, appType: 'custom', logLevel: 'silent' });
  const { Library } = await vite.ssrLoadModule('/src/components/Library.tsx');
  const root = createRoot(document.getElementById('root'));
  t.after(async () => { await React.act(async () => root.unmount()); await vite.close(); dom.window.close(); delete globalThis.window; delete globalThis.document; delete globalThis.navigator; delete globalThis.IS_REACT_ACT_ENVIRONMENT; });
  const book = (id, title, status, tags) => ({ id, title, status, tags, author: 'Autora', pages: 100, currentPage: 0, rating: 0, createdAt: 1, format: 'paperback', coverUrl: '', journal: [] });
  const books = [book('1', 'Alba', 'read', [' Fantasía ']), book('2', 'Bruma', 'pending', ['fantasía']), book('3', 'Cielo', 'read', ['Misterio'])];
  const noop = () => {};
  const props = { books, view: 'grid', onSetView: noop, onUpdate: noop, onDelete: noop, onEdit: noop, onOpen: noop, onOpenSeries: noop };
  await React.act(async () => root.render(React.createElement(Library, props)));
  const selector = document.querySelector('select[aria-label="Filtrar por etiqueta"]');
  assert.deepEqual([...selector.options].map((o) => o.textContent), ['Todas las etiquetas', 'Fantasía', 'Misterio']);
  await React.act(async () => { selector.value = 'fantasía'; selector.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  assert.ok(document.querySelector('[aria-label="Abrir ficha de Alba"]'));
  assert.ok(document.querySelector('[aria-label="Abrir ficha de Bruma"]'));
  assert.equal(document.querySelector('[aria-label="Abrir ficha de Cielo"]'), null);
  const read = [...document.querySelectorAll('button[aria-pressed]')].find((b) => b.textContent.includes('Leído'));
  assert.ok(read);
  await React.act(async () => read.click());
  assert.ok(document.querySelector('[aria-label="Abrir ficha de Alba"]'));
  assert.equal(document.querySelector('[aria-label="Abrir ficha de Bruma"]'), null);
  await React.act(async () => { selector.value = 'misterio'; selector.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  assert.ok(document.querySelector('[aria-label="Abrir ficha de Cielo"]'));
  await React.act(async () => { selector.value = 'fantasía'; selector.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  const pending = [...document.querySelectorAll('button[aria-pressed]')].find((b) => b.textContent.includes('Pendiente'));
  // Cambiar a una selección sin resultados y limpiar todos los filtros.
  await React.act(async () => pending.click());
  await React.act(async () => { selector.value = 'misterio'; selector.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  const clear = [...document.querySelectorAll('button')].find((b) => b.textContent.includes('Limpiar filtros'));
  assert.ok(clear);
  await React.act(async () => clear.click());
  assert.equal(selector.value, '');
  assert.ok(document.querySelector('[aria-label="Abrir ficha de Cielo"]'));
  await React.act(async () => root.render(React.createElement(Library, { ...props, view: 'list' })));
  await React.act(async () => { selector.value = 'misterio'; selector.dispatchEvent(new dom.window.Event('change', { bubbles: true })); });
  assert.ok(document.querySelector('[aria-label="Abrir ficha de Cielo"]'));
  assert.equal(document.querySelector('[aria-label="Abrir ficha de Alba"]'), null);
});
